def execute_waypoints(waypoints: list[dict], dry_run: bool = False):
    """Execute the waypoint sequence on the robot.

    Pick phases (home, approach_screwdriver, descend_to_grasp, close_gripper,
    retreat_upward) are executed using Cartesian IK — same proven approach as
    test_screw_continuous.py.  All other phases use the joint values from the
    waypoint file directly.
    """
    if dry_run:
        print("\n=== DRY RUN — validating only, no robot motion ===\n")
        for i, wp in enumerate(waypoints):
            phase = wp.get("phase", "?")
            phase_key = phase.lower().replace(" ", "_")
            joints = wp.get("joints", [])
            gripper = wp.get("gripper", "?")
            vs = wp.get("velocity_scaling", 0.3)
            note = wp.get("note", "")
            mode = "IK" if phase_key in PICK_PHASES else "JOINT"
            print(f"  [{i+1:2d}] {phase:<25} [{mode:>5}]  gripper={gripper}  vs={vs}  "
                  f"j=[{', '.join(f'{j:.3f}' for j in joints)}]")
            if note:
                print(f"       {note}")
        print(f"\n  Total: {len(waypoints)} waypoints — validation passed.\n")
        return

    import rclpy
    from rclpy.executors import MultiThreadedExecutor
    from sensor_msgs.msg import JointState
    from robot_agent.moveit_client import MoveItClient
    from robot_agent.gripper_client import GripperClient
    from robot_agent.recorder.joint_recorder import JointStateRecorder

    rclpy.init()
    node = make_node()
    executor = MultiThreadedExecutor(num_threads=4)
    executor.add_node(node)
    spin_thread = threading.Thread(target=executor.spin, daemon=True)
    spin_thread.start()

    try:
        node.get_logger().info("Waiting for /joint_states ...")
        if not wait_for_joint_states(node):
            node.get_logger().error("No /joint_states — is bringup running?")
            return

        moveit = MoveItClient(node)
        gripper_client = GripperClient(node)

        # Set up joint-state recorder
        recorder = JointStateRecorder(node)
        node.create_subscription(
            JointState, "/joint_states", recorder.on_joint_state, 10
        )
        node.get_logger().info("MoveIt + gripper + recorder ready.")

        # ── Pre-compute Cartesian poses for the pick sequence ──
        approach_pose = make_pose(
            SCREWDRIVER_X, SCREWDRIVER_Y, GRASP_Z + APPROACH_H,
            GRASP_QX, GRASP_QY, GRASP_QZ, GRASP_QW,
        )
        grasp_pose = make_pose(
            SCREWDRIVER_X, SCREWDRIVER_Y, GRASP_Z,
            GRASP_QX, GRASP_QY, GRASP_QZ, GRASP_QW,
        )
        retreat_pose = make_pose(
            SCREWDRIVER_X, SCREWDRIVER_Y, GRASP_Z + RETREAT_H,
            GRASP_QX, GRASP_QY, GRASP_QZ, GRASP_QW,
        )

        _last_joints[0] = list(PICK_SEED)

        print("\n" + "=" * 66)
        print("  Cosmos Waypoint Execution")
        print(f"  Waypoints: {len(waypoints)}")
        print("=" * 66)

        recorder.start_recording("cosmos_waypoint_execution")
        prev_gripper = None
        screwdriver_attached = False

        all_ok = True
        for i, wp in enumerate(waypoints):
            phase = wp.get("phase", f"step_{i}")
            phase_key = phase.lower().replace(" ", "_")
            joints = wp["joints"]
            gripper_val = wp.get("gripper")
            vs = wp.get("velocity_scaling", 0.3)
            note = wp.get("note", "")

            print(f"\n[{i+1:2d}/{len(waypoints)}] {phase}")
            if note:
                print(f"         {note}")

            t0 = time.monotonic()

            # ==============================================================
            # PICK PHASES — Cartesian IK (same as test_screw_continuous.py)
            # ==============================================================
            if phase_key == "home":
                ok = moveit.plan_and_execute_joints(HOME_JOINTS, velocity_scaling=vs)
                elapsed = time.monotonic() - t0
                print(f"         → home (joint) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                prev_gripper = gripper_val
                time.sleep(0.3)
                continue

            if phase_key == "approach_screwdriver":
                # Open gripper first
                gripper_client.open()
                prev_gripper = 0.0
                # Allow collision with screwdriver
                moveit.allow_collision("screwdriver")
                print("         → collision allowed with screwdriver")
                # IK approach
                ok = ik_and_move(moveit, approach_pose, vs, [PICK_SEED, HOME_JOINTS])
                elapsed = time.monotonic() - t0
                print(f"         → approach (IK) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                time.sleep(0.3)
                continue

            if phase_key == "descend_to_grasp":
                ok = ik_and_move(moveit, grasp_pose, vs, [_last_joints[0], PICK_SEED])
                elapsed = time.monotonic() - t0
                print(f"         → descend (IK) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                prev_gripper = 0.0
                time.sleep(0.3)
                continue

            if phase_key == "close_gripper":
                grip_pos = gripper_val if gripper_val and gripper_val > 0 else GRASP_GRIPPER_POSITION
                ok = gripper_client.set_position(grip_pos)
                prev_gripper = grip_pos
                elapsed = time.monotonic() - t0
                print(f"         → gripper close ({grip_pos:.2f}) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                # Attach screwdriver after closing gripper
                if not screwdriver_attached:
                    moveit.attach_object("screwdriver", "tool0", touch_links=GRIPPER_LINKS)
                    screwdriver_attached = True
                    print("         → screwdriver attached to tool0")
                time.sleep(0.3)
                continue

            if phase_key == "retreat_upward":
                ok = ik_and_move(moveit, retreat_pose, vs,
                                 [_last_joints[0], PICK_SEED, HOME_JOINTS])
                elapsed = time.monotonic() - t0
                print(f"         → retreat (IK) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                prev_gripper = gripper_val
                time.sleep(0.3)
                continue

            # ==============================================================
            # NON-PICK PHASES — use joint values from the waypoint file
            # ==============================================================

            # Return home — always use known HOME_JOINTS
            if phase_key == "return_home":
                ok = moveit.plan_and_execute_joints(HOME_JOINTS, velocity_scaling=vs)
                elapsed = time.monotonic() - t0
                print(f"         → return home (joint) {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                prev_gripper = gripper_val
                time.sleep(0.3)
                continue

            # Gripper-only open phase — return screwdriver to holder first
            if phase_key in GRIPPER_OPEN_PHASES:
                if screwdriver_attached:
                    ok = ik_and_move(moveit, approach_pose, 0.3,
                                     [_last_joints[0], PICK_SEED, HOME_JOINTS])
                    print(f"         → holder approach {'OK' if ok else 'FAILED'}")
                    if ok:
                        ok = ik_and_move(moveit, grasp_pose, 0.2,
                                         [_last_joints[0], PICK_SEED])
                        print(f"         → lower to holder {'OK' if ok else 'FAILED'}")
                ok = gripper_client.open()
                prev_gripper = 0.0
                elapsed = time.monotonic() - t0
                print(f"         → gripper open {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")
                if not ok:
                    all_ok = False
                    break
                if screwdriver_attached:
                    moveit.detach_object("screwdriver")
                    screwdriver_attached = False
                    print("         → screwdriver detached")
                    ik_and_move(moveit, retreat_pose, 0.3,
                                [_last_joints[0], PICK_SEED, HOME_JOINTS])
                    print("         → retreated from holder")
                time.sleep(0.3)
                continue

            # Arm motion (model-generated screwing waypoints)
            ok = moveit.plan_and_execute_joints(joints, velocity_scaling=vs)
            elapsed = time.monotonic() - t0
            print(f"         → {'OK' if ok else 'FAILED'}  ({elapsed:.2f}s)")

            if not ok:
                all_ok = False
                print("         Aborting sequence.")
                break

            # Handle gripper changes after arm motion
            if gripper_val is not None and prev_gripper is not None:
                if abs(gripper_val - prev_gripper) > 0.05:
                    if gripper_val < 0.1:
                        gripper_client.open()
                        prev_gripper = 0.0
                        print("         → gripper opened")
                    else:
                        gripper_client.set_position(gripper_val)
                        prev_gripper = gripper_val
                        print(f"         → gripper set to {gripper_val:.2f}")

            if gripper_val is not None:
                prev_gripper = gripper_val

            time.sleep(0.3)

        # ── Stop recording and save trace ──
        trace = recorder.stop_recording()
        if trace and trace.snapshots:
            out_path = save_trace(trace)
            print(f"\n  Joint trace saved → {out_path}")
            print(f"  ({len(trace.snapshots)} snapshots, {trace.duration_sec:.2f}s)")
        else:
            print("\n  WARNING: no trace snapshots recorded.")

        print("\n" + "=" * 66)
        print(f"  Result: {'SUCCESS' if all_ok else 'FAILED — see above.'}")
        print("=" * 66 + "\n")

    except KeyboardInterrupt:
        print("\nInterrupted.")
    finally:
        executor.shutdown()
        node.destroy_node()
        rclpy.shutdown()


# ---------------------------------------------------------------------------
# Entry point
# ---------------------------------------------------------------------------

def main():
    parser = argparse.ArgumentParser(
        description="Execute Cosmos-generated waypoints on UR5e and record trace"
    )
    parser.add_argument(
        "cosmos_output",
        help="Path to Cosmos 8B output JSON file (e.g., outputs/cosmos/8b/cosmos_screw_*.json)"
    )
    parser.add_argument(
        "--dry-run", action="store_true",
        help="Validate waypoints and print execution plan without moving the robot"
    )
    args = parser.parse_args()

    cosmos_path = Path(args.cosmos_output)
    if not cosmos_path.exists():
        print(f"ERROR: File not found: {cosmos_path}")
        sys.exit(1)

    print(f"\n[1] Loading Cosmos output: {cosmos_path.name}")
    waypoints = extract_waypoints(cosmos_path)
    print(f"    Found {len(waypoints)} waypoints")

    # Print phase summary
    phases = [wp.get("phase", "?") for wp in waypoints]
    print(f"    Phases: {' → '.join(phases)}")

    print(f"\n[2] Validating waypoints...")
    errors = validate_waypoints(waypoints)
    if errors:
        print("    Validation errors:")
        for e in errors:
            print(f"      {e}")
        sys.exit(1)
    print("    All waypoints valid.")

    print(f"\n[3] {'Dry run' if args.dry_run else 'Executing'}...")
    execute_waypoints(waypoints, dry_run=args.dry_run)


if __name__ == "__main__":
    main()
