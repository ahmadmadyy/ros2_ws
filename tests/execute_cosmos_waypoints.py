def repair_json(raw: str) -> str:
    """Attempt to repair truncated JSON from LLM output."""
    # Fix unescaped newlines inside string values
    raw = re.sub(r'("note"\s*:\s*"[^"]*)\n\s*', r'\1 ', raw)

    # Try parsing as-is first
    try:
        json.loads(raw)
        return raw
    except json.JSONDecodeError:
        pass

    # Try closing unclosed brackets/braces
    # Remove trailing incomplete object (partial waypoint)
    # Find last complete waypoint (ends with "}")
    last_brace = raw.rfind("}")
    if last_brace == -1:
        return raw

    # Check if we need to close the array and outer object
    trimmed = raw[:last_brace + 1]

    # Count open/close brackets to figure out what's missing
    opens = trimmed.count("[") - trimmed.count("]")
    braces = trimmed.count("{") - trimmed.count("}")

    suffix = "]" * opens + "}" * braces
    repaired = trimmed + suffix

    try:
        json.loads(repaired)
        return repaired
    except json.JSONDecodeError:
        pass

    return raw


def extract_waypoints(cosmos_json_path: Path) -> list[dict]:
    """Extract recommended_waypoints from a Cosmos output JSON file.

    Checks top-level ``recommended_waypoints`` first (written by
    run_8b_pipeline.py with pick + screwing merged).  Falls back to
    parsing the raw ``response`` text from the LLM.
    """
    with open(cosmos_json_path) as f:
        meta = json.load(f)

    # Prefer the pre-merged top-level array (includes pick + screwing)
    if isinstance(meta.get("recommended_waypoints"), list) and meta["recommended_waypoints"]:
        return meta["recommended_waypoints"]

    response_text = meta.get("response", "")

    # Strip markdown code fences if present
    json_match = re.search(r'```(?:json)?\s*(\{.*?\})\s*```', response_text, re.DOTALL)
    if json_match:
        inner = json_match.group(1)
    else:
        # Find the outermost JSON object
        brace_match = re.search(r'\{', response_text)
        if brace_match:
            inner = response_text[brace_match.start():]
        else:
            inner = response_text

    # Attempt repair for truncated/malformed JSON
    inner = repair_json(inner)

    try:
        parsed = json.loads(inner)
    except json.JSONDecodeError as e:
        print(f"ERROR: Could not parse JSON from response (even after repair): {e}")
        print(f"Response preview: {response_text[:500]}")
        sys.exit(1)

    waypoints = parsed.get("recommended_waypoints", [])
    if not waypoints:
        print("ERROR: No recommended_waypoints found in the Cosmos output.")
        print("Available keys:", list(parsed.keys()))
        sys.exit(1)

    return waypoints


def validate_waypoints(waypoints: list[dict]) -> list[str]:
    """Validate waypoint joint values against UR5e limits. Returns list of errors."""
    errors = []
    for i, wp in enumerate(waypoints):
        phase = wp.get("phase", f"waypoint_{i}")

        # Check joints array
        joints = wp.get("joints")
        if not joints or not isinstance(joints, list) or len(joints) != 6:
            errors.append(f"[{i}] {phase}: joints must be a list of 6 values, got {joints}")
            continue

        for j, (val, (lo, hi)) in enumerate(zip(joints, JOINT_LIMITS)):
            if not isinstance(val, (int, float)):
                errors.append(f"[{i}] {phase}: joint {j} is not a number: {val}")
            elif val < lo or val > hi:
                errors.append(f"[{i}] {phase}: joint {j} = {val:.4f} out of range [{lo:.4f}, {hi:.4f}]")

        # Check gripper
        gripper = wp.get("gripper")
        if gripper is not None and not isinstance(gripper, (int, float)):
            errors.append(f"[{i}] {phase}: gripper is not a number: {gripper}")

        # Check velocity_scaling
        vs = wp.get("velocity_scaling")
        if vs is not None:
            if not isinstance(vs, (int, float)) or vs <= 0 or vs > 1.0:
                errors.append(f"[{i}] {phase}: velocity_scaling must be (0, 1.0], got {vs}")

    return errors


# ---------------------------------------------------------------------------
# Trace saving
# ---------------------------------------------------------------------------

def save_trace(trace) -> Path:
    out_dir = Path(__file__).parent.parent / "outputs" / "screw_trace"
    out_dir.mkdir(parents=True, exist_ok=True)
    ts = datetime.now().strftime("%Y%m%d_%H%M%S")
    path = out_dir / f"cosmos_executed_{ts}.json"
    data = {
        "trace_id":       trace.trace_id,
        "label":          trace.label,
        "duration_sec":   round(trace.duration_sec, 4),
        "num_snapshots":  len(trace.snapshots),
        "snapshots": [
            {
                "timestamp":   round(s.timestamp, 6),
                "joint_names": s.joint_names,
                "positions":   [round(v, 6) for v in s.positions],
                "velocities":  [round(v, 6) for v in s.velocities],
            }
            for s in trace.snapshots
        ],
    }
    path.write_text(json.dumps(data, indent=2))
    return path


