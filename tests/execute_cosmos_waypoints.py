#!/usr/bin/env python3
"""
Execute waypoints generated by Cosmos 8B evaluation and record a new trace.

Reads the `recommended_waypoints` array from a Cosmos 8B output JSON file,
validates joint values, and executes them on the UR5e via MoveIt while
recording joint states for subsequent re-evaluation.

Usage
-----
    python3 tests/execute_cosmos_waypoints.py outputs/cosmos/8b/cosmos_screw_<id>_<ts>.json
    python3 tests/execute_cosmos_waypoints.py outputs/cosmos/8b/cosmos_screw_<id>_<ts>.json --dry-run

Prerequisites
-------------
    Terminal 1:  ros2 launch ur5e_robotiq_moveit_config bringup.launch.py
    Terminal 2:  python3 tests/execute_cosmos_waypoints.py <cosmos_output.json>
"""

import argparse
import json
import math
import re
import sys
import threading
import time
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent / "src" / "robot_agent"))

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------
GRIPPER_LINKS = [
    'tool0',
    'rq_robotiq_85_base_link',
    'rq_robotiq_85_left_knuckle_link',
    'rq_robotiq_85_right_knuckle_link',
    'rq_robotiq_85_left_finger_link',
    'rq_robotiq_85_right_finger_link',
    'rq_robotiq_85_left_inner_knuckle_link',
    'rq_robotiq_85_right_inner_knuckle_link',
    'rq_robotiq_85_left_finger_tip_link',
    'rq_robotiq_85_right_finger_tip_link',
]

# UR5e joint limits
JOINT_LIMITS = [
    (-2 * math.pi, 2 * math.pi),   # shoulder_pan
    (-2 * math.pi, 2 * math.pi),   # shoulder_lift
    (-math.pi, math.pi),           # elbow
    (-2 * math.pi, 2 * math.pi),   # wrist_1
    (-2 * math.pi, 2 * math.pi),   # wrist_2
    (-2 * math.pi, 2 * math.pi),   # wrist_3
]

# Phases that trigger gripper/collision actions
GRIPPER_OPEN_PHASES = {"open_gripper"}
GRIPPER_CLOSE_PHASES = {"close_gripper"}
COLLISION_ALLOW_PHASES = {"approach_screwdriver"}
ATTACH_PHASES = {"close_gripper"}
DETACH_PHASES = {"open_gripper_drop"}

# ---------------------------------------------------------------------------
# Pick geometry — same as test_screw_continuous.py
# Uses Cartesian IK so the robot always finds a valid pick solution.
# ---------------------------------------------------------------------------
SCREWDRIVER_X      = 0.45
SCREWDRIVER_Y      = 0.00
SCREWDRIVER_RADIUS = 0.012
FINGER_TIP_OFFSET  = 0.170
SCREWDRIVER_MID_Z  = 0.09
GRASP_Z    = SCREWDRIVER_MID_Z + FINGER_TIP_OFFSET   # 0.26 m
APPROACH_H = 0.18
RETREAT_H  = 0.20
GRASP_QX, GRASP_QY, GRASP_QZ, GRASP_QW = 1.0, 0.0, 0.0, 0.0
GRASP_GRIPPER_POSITION = 0.57
HOME_JOINTS = [0.0, -math.pi / 2, 0.0, -math.pi / 2, 0.0, 0.0]
PICK_SEED   = [0.0, -1.7, 1.8, -1.7, -math.pi / 2, 0.0]

# Phases that belong to the pick sequence — executed via Cartesian IK
PICK_PHASES = {"home", "approach_screwdriver", "descend_to_grasp",
               "close_gripper", "retreat_upward"}


